namespace KirosEngine3.Textures
{
    /// <summary>
    /// Defines the different modes for drawing text.
    /// </summary>
    public enum TextDrawMode
    {
        /// <summary>
        /// By individual character.
        /// </summary>
        ByChar,
        /// <summary>
        /// By individual line.
        /// </summary>
        ByLine,
        /// <summary>
        /// By block of text.
        /// </summary>
        ByBlock
    }
}